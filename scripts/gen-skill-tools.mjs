// Generate skills/<skill>/reference.md from the live MCP tool catalog.
// Run: node scripts/gen-skill-tools.mjs [entry.js]
// Spawns the server with WPS_OFFICE_TOOLSET=full so the reference lists every tool,
// including the ones only reachable through wps_call.
import { spawn } from "node:child_process";
import { writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";

const entry = process.argv[2] || "mcp/dist/index.js";
const child = spawn(process.execPath, [entry], { stdio: ["pipe", "pipe", "pipe"], windowsHide: true, env: { ...process.env, WPS_OFFICE_TOOLSET: "full" } });
let buf = "";
const pending = new Map();
function send(o) { child.stdin.write(JSON.stringify(o) + "\n"); }
function req(id, method, params) { return new Promise((resolve) => { pending.set(id, resolve); send({ jsonrpc: "2.0", id, method, params }); }); }
child.stdout.on("data", (d) => { buf += d.toString(); let i; while ((i = buf.indexOf("\n")) >= 0) { const line = buf.slice(0, i).trim(); buf = buf.slice(i + 1); if (!line) continue; let m; try { m = JSON.parse(line); } catch { continue; } if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } } });
child.stderr.on("data", () => {});

await req(1, "initialize", { protocolVersion: "2025-06-18", capabilities: {}, clientInfo: { name: "gen-skills", version: "1.0.0" } });
send({ jsonrpc: "2.0", method: "notifications/initialized" });
const res = await req(2, "tools/list", {});
const tools = (res.result && res.result.tools) || [];

// The advertised surface comes from the same module the server uses, so it cannot drift.
const require = createRequire(import.meta.url);
const toolset = require("../mcp/dist/server/toolset.js");
const standard = new Set([...(toolset.FACADE_TOOLS || []), ...(toolset.STANDARD_TOOLS || [])]);;

function firstSentence(text, max) {
  const flat = (text || "").replace(/\s+/g, " ").trim();
  const stop = flat.search(/[。.!?]/);
  const cut = stop >= 0 && stop + 1 <= max ? flat.slice(0, stop + 1) : flat.slice(0, max);
  return cut.replace(/\|/g, "/");
}
function bucket(name) {
  const m = /^wps_(excel|word|ppt)_/.exec(name);
  if (m) return m[1];
  if (/^wps_(common|convert)_/.test(name)) return "common";
  if (["wps_status", "wps_help", "wps_call", "wps_batch"].includes(name)) return "facade";
  return "builtin";
}

const groups = { facade: [], common: [], excel: [], word: [], ppt: [], builtin: [] };
for (const t of tools) groups[bucket(t.name)].push(t);

const titles = {
  facade: "门面工具（始终广告）",
  common: "通用与转换工具",
  excel: "WPS 表格工具",
  word: "WPS 文字工具",
  ppt: "WPS 演示工具",
  builtin: "内置兼容工具"
};
const files = {
  facade: "skills/wps-office-next/reference.md",
  common: "skills/wps-office-next/reference.md",
  builtin: "skills/wps-office-next/reference.md",
  excel: "skills/wps-excel/reference.md",
  word: "skills/wps-word/reference.md",
  ppt: "skills/wps-ppt/reference.md"
};

const sections = {};
for (const key of ["facade", "common", "excel", "word", "ppt", "builtin"]) {
  const rows = groups[key].map((t) => {
    const mark = standard.has(t.name) ? "直达" : "wps_call";
    return "| " + t.name + " | " + mark + " | " + firstSentence(t.description, 90) + " |";
  });
  sections[key] = [
    "## " + titles[key] + "（" + groups[key].length + "）",
    "",
    "| 工具 | 在 standard 档 | 说明 |",
    "|---|---|---|",
    ...rows,
    ""
  ].join("\n");
}

const header = [
  "<!-- GENERATED by scripts/gen-skill-tools.mjs - do not edit by hand. -->",
  "",
  "本文件由实时工具目录生成，列出全部工具，供 wps_call 派发时查名。",
  "“直达”表示 standard 档直接广告；“wps_call”表示需要用 wps_call 调用（先用 wps_help 取参数 schema）。",
  ""
].join("\n");

const out = {
  "skills/wps-office-next/reference.md": [header, sections.facade, sections.common, sections.builtin].join("\n"),
  "skills/wps-excel/reference.md": [header, sections.excel].join("\n"),
  "skills/wps-word/reference.md": [header, sections.word].join("\n"),
  "skills/wps-ppt/reference.md": [header, sections.ppt].join("\n")
};

for (const [path, content] of Object.entries(out)) {
  mkdirSync(path.split("/").slice(0, -1).join("/"), { recursive: true });
  writeFileSync(path, content);
  console.log("wrote " + path + " (" + content.split("\n").length + " lines)");
}
// ---- SKILL.md 里「会漂的数字」改成生成物（FIXES 75）--------------------------------------------------
// 这几段以前是手写的，于是 reference.md 由 CI 对账、SKILL.md 的数字却悄悄烂掉（44 vs 69、演示「96 个」
// vs 76、表格「80 多个」vs 92）。把清单与计数圈进标记里由生成器维护，标记缺失就让生成失败 ——
// 手写数字不再有第二次漂移的机会。
const MARK_START = "<!-- GENERATED:advertised:start -->";
const MARK_END = "<!-- GENERATED:advertised:end -->";
const advertisedNames = (key) => groups[key].filter((t) => standard.has(t.name)).map((t) => t.name).sort();
function rewriteAdvertised(path, body) {
  const text = readFileSync(path, "utf8");
  const start = text.indexOf(MARK_START);
  const end = text.indexOf(MARK_END);
  if (start < 0 || end < start) throw new Error(path + " 缺少 GENERATED:advertised 标记");
  writeFileSync(path, text.slice(0, start) + [MARK_START, body, MARK_END].join("\n") + text.slice(end + MARK_END.length));
  console.log("updated " + path + " (advertised block)");
}
const countsByApp = { facade: advertisedNames("facade").length, common: advertisedNames("common").length, excel: advertisedNames("excel").length, word: advertisedNames("word").length, ppt: advertisedNames("ppt").length };
const totalAdvertised = Object.values(countsByApp).reduce((a, b) => a + b, 0);
const commonLine = "通用工具（" + countsByApp.common + " 个，三个应用共用）：" + advertisedNames("common").join("、");
rewriteAdvertised("skills/wps-office-next/SKILL.md", "默认 standard 档直接广告 **" + totalAdvertised + "** 个工具（门面 " + countsByApp.facade + " / 通用 " + countsByApp.common + " / 表格 " + countsByApp.excel + " / 文字 " + countsByApp.word + " / 演示 " + countsByApp.ppt + "），其余 " + (tools.length - totalAdvertised) + " 个工具仍然完全可用：");
for (const key of ["excel", "word", "ppt"]) {
  const label = { excel: "表格", word: "文字", ppt: "演示" }[key];
  const own = advertisedNames(key);
  rewriteAdvertised("skills/wps-" + key + "/SKILL.md", "直接广告的 " + own.length + " 个" + label + "工具（其余 " + (groups[key].length - own.length) + " 个用 wps_call，清单见同目录 reference.md）：\n\n" + own.join("、") + "\n\n" + commonLine);
}
console.log("total tools=" + tools.length + " advertised=" + tools.filter((t) => standard.has(t.name)).length);
child.kill();
process.exit(0);
